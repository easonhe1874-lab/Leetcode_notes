"""
LeetCode 66. 加一 (Plus One)

【题目描述】
给定一个由整数组成的非空数组，表示一个非负整数。在该数的基础上加一。

【深度分析与坑点】
1. 避坑指南：切忌将数组先拼接成字符串/大整数再 +1 转回数组！在 Python 中虽然支持大整数，但在 C++/Java 中会导致溢出，且不符合算法考核本质。
2. 核心逻辑：从数组末尾（个位）倒序向前遍历：
   - 若当前位数字 < 9：直接 +1 并返回数组（无后续进位，提前结束）。
   - 若当前位数字 == 9：加 1 后产生进位，该位变为 0，继续向高位处理。
3. 边界处理：若遍历结束仍未返回（如 [9, 9, 9] 变为了 [0, 0, 0]），说明最高位产生了进位，直接在首位插入 1，返回 [1, 0, 0, 0]。

【复杂度分析】
- 时间复杂度: O(N)，最坏情况下（如全 9 数组）遍历一次整个数组。
- 空间复杂度: O(1)，除了特例情况新建返回列表外，均为原地修改。
"""

class Solution:
    def plusOne(self, digits: list[int]) -> list[int]:
        # 从末尾倒序遍历
        for i in range(len(digits) - 1, -1, -1):
            if digits[i] < 9:
                digits[i] += 1
                return digits
            digits[i] = 0
            
        # 处理全 9 进位特例
        return [1] + digits
